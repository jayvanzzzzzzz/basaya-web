import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { setImmediate as flush } from 'node:timers/promises';
const require=createRequire(new URL('../notify-api/package.json',import.meta.url));
const {parseHTML}=require('linkedom');
const {document,window}=parseHTML('<html><body><div id="modal" style="overflow:hidden"><button data-floating-tooltip aria-label="Add word to dictionary" aria-describedby="existing-help"><svg></svg></button></div></body></html>');
window.innerWidth=400;window.innerHeight=300;
const root=document.querySelector('#modal'),button=root.querySelector('button');
let bounds={left:325,right:365,top:4,bottom:44,width:40,height:40};
button.getBoundingClientRect=()=>bounds;
const original=window.Element.prototype.getBoundingClientRect;
window.Element.prototype.getBoundingClientRect=function(){return this.classList?.contains('floating-tooltip')?{width:180,height:34}:original.call(this)};
const source=await readFile(new URL('../js/floatingTooltip.js',import.meta.url),'utf8');
const attach=new Function('document','window','MutationObserver',source.replace('export function ','function ')+';return attachFloatingTooltips;')(document,window,window.MutationObserver);
const dispose=attach(root);
const event=(type,extra={})=>Object.assign(new window.Event(type,{bubbles:true,cancelable:true}),extra);
button.querySelector('svg').dispatchEvent(event('pointerover'));
const tooltip=document.querySelector('[role="tooltip"]');
assert.equal(tooltip.parentElement,document.body,'Tooltip escapes the modal clipping container');
assert.equal(root.contains(tooltip),false);
assert.equal(tooltip.hidden,false);
assert.equal(tooltip.textContent,'Add word to dictionary');
assert.ok(parseInt(tooltip.style.left)>=8&&parseInt(tooltip.style.left)+180<=392,'Tooltip stays inside the viewport');
assert.equal(parseInt(tooltip.style.top),52,'Near the top edge, show below the icon');
assert.equal(button.getAttribute('aria-describedby'),`existing-help ${tooltip.id}`);
button.dispatchEvent(event('focusin'));
button.dispatchEvent(event('pointerout',{relatedTarget:null}));
assert.equal(tooltip.hidden,false,'Keyboard focus keeps the tooltip visible');
bounds={left:8,right:48,top:150,bottom:190,width:40,height:40};
window.dispatchEvent(event('resize'));
assert.equal(parseInt(tooltip.style.left),8);
assert.equal(parseInt(tooltip.style.top),108);
button.dispatchEvent(event('keydown',{key:'Escape'}));
assert.equal(tooltip.hidden,true);
assert.equal(button.getAttribute('aria-describedby'),'existing-help');
button.dispatchEvent(event('focusin'));
button.disabled=true;await flush();
assert.equal(tooltip.hidden,true,'A disabled or removed action cannot leave a stale tooltip');
button.disabled=false;button.dispatchEvent(event('pointerover'));
button.dispatchEvent(event('click'));assert.equal(tooltip.hidden,true,'Opening the dictionary dismisses the tooltip');
dispose();assert.equal(document.querySelector('[role="tooltip"]'),null);
console.log('PASS: tooltip outside modal overflow, full label, viewport edge placement, keyboard focus, Escape, click dismissal, cleanup');
