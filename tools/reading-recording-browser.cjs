// Synthetic visual/layout check. No real account, recording, or production API.
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const path = require('node:path');
const os = require('node:os');
const { chromium } = require('C:/Users/Scean Andrei/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root = path.resolve(__dirname, '..');
let server, browser;
(async () => {
  server = spawn(process.execPath, ['tools/serve-fluency-preview.mjs'], { cwd: root, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
  await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(Error('Fixture did not start')), 30000);
    server.stdout.on('data', data => { if (data.toString().includes('Reading fixture:')) { clearTimeout(timeout); resolve(); } });
    server.once('exit', code => { clearTimeout(timeout); reject(Error(`Fixture exited ${code}`)); });
  });
  browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8794/?stage=preview');
  await page.locator('[data-reading-play]').waitFor();
  assert.equal(await page.locator('audio[controls]').count(), 0);
  assert.equal(await page.locator('[data-reading-mic]').count(), 0);
  const preview = path.join(os.tmpdir(), 'basaya-reading-preview.png');
  await page.screenshot({ path: preview, fullPage: true });
  await page.locator('[data-reading-retake]').click();
  await page.locator('[data-reading-mic]').waitFor();
  assert.equal(await page.locator('#reading-preview').count(), 0);
  assert.equal(await page.locator('[data-reading-next]').count(), 0);
  await page.waitForTimeout(350);
  const dimensions = await page.evaluate(() => {
    const card = document.querySelector('.st-reading__card').getBoundingClientRect();
    const mic = document.querySelector('[data-reading-mic]').getBoundingClientRect();
    return { overflow: document.documentElement.scrollWidth > innerWidth, gap: mic.top - card.bottom };
  });
  assert.equal(dimensions.overflow, false); assert.ok(dimensions.gap < 180, 'Microphone stays near the sentence');
  const retake = path.join(os.tmpdir(), 'basaya-reading-retake.png');
  await page.screenshot({ path: retake, fullPage: true });
  await page.locator('[data-reading-keep]').click();
  await page.locator('[data-reading-play]').waitFor();
  await page.evaluate(() => document.documentElement.dataset.theme = 'dark');
  const dark = path.join(os.tmpdir(), 'basaya-reading-preview-dark.png');
  await page.screenshot({ path: dark, fullPage: true });
  await page.goto('http://127.0.0.1:8794/?check=wait');
  const mic=page.locator('[data-reading-mic]');await mic.waitFor();
  const word=await page.locator('.st-reading__text').textContent();
  await mic.dispatchEvent('pointerdown',{pointerType:'mouse',button:0,pointerId:1});
  await page.waitForTimeout(60);await mic.dispatchEvent('pointerup');
  await page.locator('.st-reading__checking').waitFor();
  assert.equal(await page.locator('.st-reading__checking-bars i').count(),5);
  assert.equal(await mic.isDisabled(),true);
  assert.equal(await page.locator('.st-reading__text').textContent(),word,'Checking keeps the spoken word on screen');
  const checking=path.join(os.tmpdir(),'basaya-reading-checking.png');
  await page.screenshot({path:checking,fullPage:true});
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('.st-reading__checking-bars i').first().evaluate(bar=>getComputedStyle(bar).animationName),'none');
  await page.evaluate(()=>window.finishWordCheck());
  await page.locator('.st-reading__checking').waitFor({state:'detached'});
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'PASS', preview, retake, dark, checking, dimensions }));
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); server?.kill(); });
