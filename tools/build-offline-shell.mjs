import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const root = new URL("../", import.meta.url);
async function files(folder, accept) {
  const result = [];
  for (const entry of await readdir(new URL(folder, root), { withFileTypes: true })) {
    const path = `${folder}${entry.name}`;
    if (entry.isDirectory()) result.push(...await files(`${path}/`, accept));
    else if (accept(path)) result.push(path);
  }
  return result;
}
const shell = ["offline.html", "manifest.webmanifest", "firebase-config.js",
  ...await files("student/", (p) => p.endsWith(".js") || p === "student/index.html"),
  ...await files("js/", (p) => p.endsWith(".js")),
  ...await files("css/", (p) => p.endsWith(".css")),
  ...await files("img/", () => true), "data/dictionary/tl-seed.json"];
const sdk = new Set();
for (const path of shell.filter((p) => p.endsWith(".js"))) {
  const source = await readFile(new URL(path, root), "utf8");
  for (const url of source.matchAll(/https:\/\/www\.gstatic\.com\/firebasejs\/[^"'\s]+\.js/g)) sdk.add(url[0]);
}
const hash = createHash("sha256");
for (const path of [...shell].sort()) hash.update(path).update(await readFile(new URL(path, root)));
const version = hash.digest("hex").slice(0, 12);
await writeFile(new URL("offline-shell.js", root), `// Generated by node tools/build-offline-shell.mjs\nself.BASAYA_VERSION = "${version}";\nself.BASAYA_SHELL = ${JSON.stringify(shell.sort(), null, 2)};\nself.BASAYA_SDK = ${JSON.stringify([...sdk].sort(), null, 2)};\n`);
console.log(`Offline shell: ${shell.length} files, ${sdk.size} Firebase entry modules`);
