async function load(url) {
  if(modules.has(url.href)) return modules.get(url.href);
  let exports;
  if(url.pathname.endsWith('/lib/firebase.js')) exports={db:()=>firestore,adminAuth:()=>authentication};
  if(url.pathname.endsWith('/lib/http.js')) exports={allowCors:()=>{},requireToken:async(req,res)=>{if(req.headers.authorization)return {uid:req.headers.authorization};res.status(401).json({error:'Not signed in'});return null;}};
  if(url.pathname.endsWith('/lib/rateLimit.js')) exports={withinRateLimit:async()=>!limited};
  const module=exports?new vm.SyntheticModule(Object.keys(exports),function(){for(const [k,v] of Object.entries(exports))this.setExport(k,v);},{context,identifier:url.href}):new vm.SourceTextModule(await readFile(url,'utf8'),{context,identifier:url.href});
  modules.set(url.href,module);
  if(!exports) await module.link((specifier,parent)=>load(new URL(specifier,parent.identifier)));
  return module;
}
