import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { startFirestoreTestServer } from './firestore-test-server.mjs';
import { changeEnrollment, changeClassArchive } from '../notify-api/lib/enrollmentLifecycle.js';
import { archiveClassMember } from '../notify-api/lib/classProgress.js';
import { context } from '../notify-api/lib/assessments.js';
import { lessonDeadline,monitoringTime } from '../js/deadline-policy.js';
const emulator=await startFirestoreTestServer(...process.argv.slice(2));
process.env.FIRESTORE_EMULATOR_HOST=emulator.host;
const require=createRequire(new URL('../notify-api/package.json',import.meta.url));
const {initializeApp,deleteApp}=require('firebase-admin/app');
const {getFirestore,Timestamp}=require('firebase-admin/firestore');
const app=initializeApp({projectId:emulator.project},'enrollment-lifecycle'),db=getFirestore(app);
const classId='class1',uid='learner',now=Date.now();
const userRef=db.doc('users/'+uid),rosterRef=db.doc(`classes/${classId}/students/${uid}`),classRef=db.doc('classes/'+classId),progressRef=userRef.collection('assignedLessons').doc('lesson');
const request={classId,lessonId:'lesson',progressSession:'saved-session'};
const authorize=body=>db.runTransaction(tx=>context(tx,db,uid,body,{open:false}));
const patch=async(path,fields,uid)=>fetch(`${emulator.documents}/${path}?${Object.keys(fields).map(key=>'updateMask.fieldPaths='+key).join('&')}`,{method:'PATCH',headers:{Authorization:'Bearer '+emulator.token(uid),'Content-Type':'application/json'},body:JSON.stringify({fields})});
try {
  await db.doc('users/teacher').set({role:'teacher'});
  await db.doc('users/admin').set({role:'admin'});
  await classRef.set({teacherId:'teacher',className:'Test class',classCode:'JOINME'});
  await userRef.set({role:'student',classId,progressSession:'saved-session'});
  await rosterRef.set({fullName:'Learner',joinedAt:Timestamp.fromMillis(now-10000)});
  await classRef.collection('classLessons').doc('lesson').set({lessonId:'lesson'});
  const saved={lectureResumePage:2,quizScore:8,quizTotal:10,quizFinished:true,progressSession:'saved-session'};
  await progressRef.set(saved);
  await authorize(request);
  await assert.rejects(changeEnrollment(db,'other',classId,uid,'drop'),error=>error.status===403);
  await assert.rejects(changeEnrollment(db,'admin',classId,uid,'drop'),error=>error.status===403);
  assert.equal((await changeEnrollment(db,'teacher',classId,uid,'drop')).status,'dropped');
  assert.equal((await rosterRef.get()).get('membershipStatus'),'dropped');
  assert.equal((await userRef.get()).get('classId'),classId);
  assert.deepEqual((await progressRef.get()).data(),saved,'All completed and partial saved work survives dropping');
  assert.equal((await userRef.get()).get('disabled'),undefined,'Drop does not deactivate the account');
  await db.runTransaction(tx=>context(tx,db,uid,request,{open:false,historicalTeacher:'teacher'}));
  await assert.rejects(db.runTransaction(tx=>context(tx,db,uid,request,{open:false,historicalTeacher:'other'})),error=>error.status===403);
  const droppedVersion=(await userRef.get()).get('enrollmentVersion');
  await assert.rejects(authorize({...request,enrollmentVersion:droppedVersion}),error=>error.status===403);
  assert.equal((await changeEnrollment(db,'teacher',classId,uid,'drop')).unchanged,true);
  assert.equal((await rosterRef.get()).get('droppedPeriods').length,1,'Retry does not create another interval');
  const droppedAt=(await rosterRef.get()).get('droppedPeriods')[0].start;
  assert.equal(monitoringTime({},now+10000,(await rosterRef.get()).data()),droppedAt);
  assert.equal(lessonDeadline({id:'lesson',dueAt:droppedAt},{...(await rosterRef.get()).data()}).exempt,true);
  await userRef.update({disabled:true});
  await assert.rejects(changeEnrollment(db,'teacher',classId,uid,'reenroll'),error=>error.status===409);
  await userRef.update({disabled:false});
  // Establish an elapsed deadline inside the interval independently of clock resolution.
  await rosterRef.update({droppedPeriods:[{start:now-1000,end:null}]});
  assert.equal((await changeEnrollment(db,'teacher',classId,uid,'reenroll')).status,'enrolled');
  const version=(await userRef.get()).get('enrollmentVersion');
  assert.notEqual(version,droppedVersion);
  assert.equal(lessonDeadline({id:'lesson',dueAt:now},{...(await rosterRef.get()).data()}).exempt,true,'Deadline exemptions survive re-enrollment');
  await assert.rejects(authorize({...request,enrollmentVersion:droppedVersion}),error=>error.status===409,'Old offline submissions cannot replay after re-enrollment');
  await authorize({...request,enrollmentVersion:version});
  assert.deepEqual((await progressRef.get()).data(),saved);
  await assert.rejects(changeClassArchive(db,'other',classId,'archive'),error=>error.status===403);
  await changeClassArchive(db,'teacher',classId,'archive');
  assert.equal((await classRef.get()).get('archived'),true);
  assert.ok((await rosterRef.get()).exists);assert.deepEqual((await progressRef.get()).data(),saved);
  const archivedVersion=(await classRef.get()).get('classVersion');
  await assert.rejects(authorize({...request,enrollmentVersion:version,classVersion:archivedVersion}),error=>error.status===403);
  await assert.rejects(changeEnrollment(db,'teacher',classId,uid,'drop'),error=>error.status===403);
  assert.equal((await changeClassArchive(db,'teacher',classId,'archive')).unchanged,true);
  await classRef.update({archivePeriods:[{start:now-1000,end:null}]});
  await changeClassArchive(db,'teacher',classId,'restore');
  const classroom=(await classRef.get()).data();
  assert.equal(classroom.archived,false);assert.equal(classroom.membershipClosed,false);
  assert.notEqual(classroom.classVersion,archivedVersion);
  assert.equal(lessonDeadline({id:'lesson',dueAt:now},{},{},classroom).exempt,true);
  await assert.rejects(authorize({...request,enrollmentVersion:version,classVersion:archivedVersion}),error=>error.status===409);
  await authorize({...request,enrollmentVersion:version,classVersion:classroom.classVersion});
  await changeEnrollment(db,'teacher',classId,uid,'drop');await changeClassArchive(db,'teacher',classId,'archive');await changeClassArchive(db,'teacher',classId,'restore');
  assert.equal((await rosterRef.get()).get('membershipStatus'),'dropped','Restoring class never re-enrolls dropped students');
  await db.doc('lessons/lesson').set({title:'Lesson'});
  const read=async path=>fetch(`${emulator.documents}/${path}`,{headers:{Authorization:'Bearer '+emulator.token(uid)}});
  assert.equal((await read('lessons/lesson')).status,403,'Dropped student cannot fetch lesson content directly');
  assert.equal((await read(`classes/${classId}`)).status,200,'Class identity and teacher contact remain readable');
  assert.equal((await patch('users/'+uid,{enrollmentStatus:{stringValue:'enrolled'}},uid)).status,403);
  assert.equal((await patch(`classes/${classId}/students/${uid}`,{membershipStatus:{stringValue:'enrolled'}},'teacher')).status,403);
  assert.equal((await patch(`classes/${classId}`,{archivePeriods:{arrayValue:{values:[]}}},'teacher')).status,403);
  await changeEnrollment(db,'teacher',classId,uid,'reenroll');
  assert.equal((await read('lessons/lesson')).status,200);
  await changeClassArchive(db,'teacher',classId,'archive');
  assert.equal((await read('lessons/lesson')).status,403,'Archived class cannot fetch lesson content directly');
  assert.equal((await read(`users/${uid}/assignedLessons/lesson`)).status,200,'Saved progress stays readable');
  assert.equal((await patch(`classes/${classId}/students/${uid}`,{leaveRequest:{mapValue:{fields:{reason:{stringValue:'Moving class'},requestedAt:{timestampValue:new Date(now).toISOString()}}}}},uid)).status,200,'Archived student can request leave');
  assert.equal((await patch(`classes/${classId}/students/${uid}`,{leaveRequest:{nullValue:null},leaveDeclined:{mapValue:{fields:{note:{stringValue:'Please discuss first'}}}}},'teacher')).status,200,'Assigned teacher can decline while archived');
  assert.equal((await patch(`classes/${classId}/students/${uid}`,{leaveRequest:{nullValue:null}},'other')).status,403,'Other teachers cannot review requests');
  await assert.rejects(archiveClassMember(db,'teacher',classId,uid),error=>error.status===403,'Archived class does not permit removal without a leave request key');
  await changeClassArchive(db,'admin',classId,'restore');
  await changeClassArchive(db,'admin',classId,'archive');
  assert.equal((await classRef.get()).get('archivedBy'),'admin','Admin uses the same archive lifecycle');
  await rosterRef.update({leaveRequest:{requestedAt:Timestamp.fromMillis(now)}});
  await assert.rejects(archiveClassMember(db,'teacher',classId,uid,'stale-request'),error=>error.status===409);
  assert.ok((await rosterRef.get()).exists);
  await db.doc('users/teacher').update({disabled:true});
  await assert.rejects(archiveClassMember(db,'teacher',classId,uid,uid+':'+now+':'+((now%1000)*1000000)),error=>error.status===403,'Deactivated teacher cannot approve archived leave');
  await db.doc('users/teacher').update({disabled:false});
  await archiveClassMember(db,'teacher',classId,uid,uid+':'+now+':'+((now%1000)*1000000));
  assert.equal((await rosterRef.get()).exists,false,'Approved leave remains distinct from drop');
  assert.equal((await classRef.get()).get('archived'),true,'Approving leave never restores the class');
  assert.equal((await userRef.get()).get('classId'),undefined);
  assert.equal((await userRef.get()).get('enrollmentStatus'),undefined);
  const history=(await userRef.collection('classProgress').doc(classId).get()).data();
  const archive=(await userRef.collection('classProgress').doc(classId).collection('archives').doc(history.latestArchiveId).get()).data();
  assert.ok(archive.droppedPeriods.length>0,'Dropped intervals survive an actual leave archive');
  assert.deepEqual((await userRef.collection('classProgress').doc(classId).collection('archives').doc(history.latestArchiveId).collection('lessons').doc('lesson').get()).data(),saved,'Archived-class leave preserves all saved progress');
  console.log('PASS: real Firestore drop/re-enroll and archive/restore preserve all work, enforce teacher ownership, reject stale offline requests, preserve elapsed deadline exemptions, keep dropped students dropped after restoration and protect lifecycle fields/content with rules.');
} finally {await db.terminate();await deleteApp(app);await emulator.stop();}
