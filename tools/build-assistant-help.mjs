import { readFile, writeFile } from "node:fs/promises";
// Vercel's deploy root is notify-api/. Bundle the public help facts inside it.
const source = await readFile(new URL("../js/assistantHelp.js", import.meta.url), "utf8");
await writeFile(new URL("../notify-api/lib/assistantHelp.js", import.meta.url), `// Generated by node tools/build-assistant-help.mjs; edit js/assistantHelp.js.\n${source}`);
console.log("Assistant help bundled for backend.");
const handbook = await readFile(new URL("../js/handbookHelp.js", import.meta.url), "utf8");
await writeFile(new URL("../notify-api/lib/handbookHelp.js", import.meta.url), `// Generated by node tools/build-assistant-help.mjs; edit js/handbookHelp.js.\n${handbook}`);
// The native app reads the same guides as JSON; platform wording is shared.
const { assistantHelp } = await import('../js/assistantHelp.js');
const androidHelp = JSON.stringify(assistantHelp, null, 2) + '\n';
await writeFile(new URL('../build/assistant-help.json', import.meta.url), androidHelp);
if (process.argv[2]) {
  const { resolve, join } = await import('node:path');
  const target = join(resolve(process.argv[2]), 'app/src/main/assets/assistant-help.json');
  await writeFile(target, androidHelp);
  console.log(`Android assistant guides synced: ${target}`);
}
